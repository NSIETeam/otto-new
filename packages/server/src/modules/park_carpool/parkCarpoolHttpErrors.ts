export function publicCarpoolError(error: unknown): {status: number; message: string} {
  const message = error instanceof Error ? error.message : '';
  const fieldError = /^(?:出行日期|出发地|目的地)(?:不能为空|坐标无效|不能超过 (?:10|160) 个字符)$|^(?:集合点名称|地点名称|首条消息|目标账号|举报原因|提交的消息内容|处理说明)无效$/u.test(message);
  if (!publicMessages.has(message) && !fieldError) return {status: 500, message: '拼车助手请求失败，请稍后重试'};
  const status = /账号不可用|未启用园区服务|尚未绑定园区|无权/u.test(message) ? 403
    : /其他操作更新|已更新|正在处理/u.test(message) ? 409
    : /地图服务|地图图片|地图坐标转换/u.test(message) ? 503 : 400;
  return {status, message};
}
